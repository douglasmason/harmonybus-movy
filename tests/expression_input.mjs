import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const {cloudPointer,createCloudMpeInput,readCloud}=await import(pathToFileURL(resolve(process.argv[2],'dist/esm/seq/cloud-view.js')));
const bounds={left:0,top:0,width:1000,height:1000};
const first=cloudPointer({clientX:500,clientY:500,pointerType:'pen',pressure:0},bounds);
const second=cloudPointer({clientX:500.1,clientY:500,pointerType:'pen',pressure:.8},bounds);
assert(second.x>first.x,'subpixel movement survives the 7-bit grid');assert.equal(first.pressure,1,'zero force is not a release');
assert.equal(cloudPointer({clientX:0,clientY:0}, {...bounds,width:0}),null);
const precise=readCloud('cf2|8193,10001,80|8194,10002,90,0|');
assert.equal(precise.contacts[0].x,8193/16383);assert(precise.trails[0].x>precise.contacts[0].x);
assert.deepEqual(readCloud('cf1|64,64,127||'),readCloud('cf2|8256,8256,127||'));
assert.equal(readCloud('cf2|16384,10,80||'),null);
const events=[],mpe=createCloudMpeInput(event=>events.push(event));
mpe.midi([0xe1,1,64]);mpe.midi([0xb1,74,91]);assert.equal(events.length,0,'expression before note-on cannot acquire');
mpe.midi([0x91,60,100]);assert.equal(events.at(-1).action,'down');assert.equal(events.at(-1).id,113);assert.equal(events.at(-1).y,91*129);
const initial=events.at(-1).x;mpe.midi([0xe1,2,64]);assert(events.at(-1).x>initial,'14-bit bend low byte reaches X');
mpe.midi([0x92,64,70]);assert.equal(events.at(-1).id,114);mpe.midi([0xd1,0]);assert.equal(events.at(-1).id,113);assert.equal(events.at(-1).pressure,1);
const before=events.length;mpe.midi([0x81,59,0]);assert.equal(events.length,before,'stale note-off cannot release a different note');
mpe.midi([0xb1,101,0]);mpe.midi([0xb1,100,0]);mpe.midi([0xb1,6,12]);mpe.midi([0xe1,0,0]);assert.equal(events.at(-1).x,48*129);
mpe.release();mpe.midi([0x91,60,100]);assert.equal(events.at(-1).x,48*129,'UI release preserves the controller bend configuration');
mpe.midi([0x92,64,70]);
mpe.midi([0xb0,101,0]);mpe.midi([0xb0,100,6]);mpe.midi([0xb0,6,1]);assert.equal(events.at(-1).id,114);assert.equal(events.at(-1).action,'up');
assert.equal(mpe.midi([0x92,65,100]),false,'disabled members cannot acquire');
mpe.midi([0xb0,123,0]);assert.equal(events.at(-1).id,113);assert.equal(events.at(-1).action,'up');
const released=events.length;mpe.midi([0xe1,80,64]);mpe.midi([0xd1,90]);assert.equal(events.length,released);
mpe.reset();mpe.midi([0x9f,80,100]);assert.equal(events.at(-1).id,127);mpe.reset();assert.equal(events.at(-1).action,'up');
for(const data of [[0xd1],[0xe1,0,128],[0x91,-1,100],[0x91,60,NaN],[0x91,60,100,0]])assert.equal(mpe.midi(data),false);
console.log('Expression input: precise X/Y, pressure lifecycle, MPE members, low-byte bends, RPN, reset and validation pass');
