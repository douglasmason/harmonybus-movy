export const NATIVE_FONT_HEIGHT=8;
const atlas=(source)=>new Map(Object.entries(source).map(([letter,bitmap])=>{
    const rows=bitmap.split('/');
    const width=rows[0].length;
    const runs=rows.flatMap((row,y)=>{
        const result=[];
        for(let x=0;x<width;){
            if(row[x]!=='1'){x++;continue;}
            const start=x;
            while(x<width&&row[x]==='1')x++;
            result.push([start,y,x-start]);
        }
        return result;
    });
    return [letter,{width,runs}];
}));
const CAPITAL_GLYPHS=atlas(UPPER);
const REGULAR_GLYPHS=atlas(REGULAR);
const SMOOTH_GLYPHS=atlas(SMOOTH);
function glyphFor(letter,face){
    const code=face==='upper'?letter.toUpperCase():letter;
    if(code>='a'&&code<='z')return (face==='regular'?REGULAR_GLYPHS:SMOOTH_GLYPHS).get(code);
    return CAPITAL_GLYPHS.get(code)??CAPITAL_GLYPHS.get('?');
}
export function nativeTextWidth(text,face='smooth'){
    let width=0;
    for(const letter of String(text))width+=glyphFor(letter,face).width+1;
    return Math.max(0,width-1);
}
export function drawNativeText(ctx,x,y,text,face='smooth',color=1){
    let left=x;
    for(const letter of String(text)){
        const glyph=glyphFor(letter,face);
        for(const [dx,dy,width] of glyph.runs)ctx.fillRect(left+dx,y+dy,width,1,color);
        left+=glyph.width+1;
    }
    return left-x-1;
}
