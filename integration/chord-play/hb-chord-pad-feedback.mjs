import './hb-grid.mjs';
import assert from 'node:assert/strict';
const {setGridEnabled}=await import('../dist/esm/seq/grid.js');
const chord=await import('../dist/esm/seq/chord-play.js');
const {appState}=await import('../dist/esm/app/state.js');
const {seqState}=await import('../dist/esm/seq/state.js');
const {portFor}=await import('../dist/esm/track/registry.js');
const {selectTrack}=await import('../dist/esm/track/focus.js');
const {invalidateInputModeLeds,cachedSetAnimLED}=await import('../dist/esm/seq/led-cache.js');
const {keyboardState,padMapFor}=await import('../dist/esm/keyboard/state.js');
let now=30000;Date.now=()=>now;
setGridEnabled(false);selectTrack(3);seqState.sessionMode=false;chord.restoreChord(null);chord.setChordEnabled(true);
keyboardState.mode=0;keyboardState.layout=0;keyboardState.octave[3]=4;
const port=portFor(3),get=port.getParam;let mask=0;
port.getParam=key=>/:(pad_view|pad_render)$/.test(key)?'145,145,2741,0,0,6,0,3,0,0|colors2,0|playcolor1,3|playpads1,'+mask:get(key);
let rejected=false;const frames=[];
globalThis.move_midi_cable_send=(cable,packets)=>{if(cable===0){frames.push([...packets]);return !rejected;}return true;};
const step=()=>{now+=100;globalThis.tick();};
// A busy settings panel would previously consume the budget ahead of the pad frame.
chord.chordPage().pollOperationFeedback=()=>{for(let i=0;i<16;i++)cachedSetAnimLED(16+i,(now/100)%2?3:11,0,0);};
invalidateInputModeLeds();rejected=true;step();
assert(frames.some(frame=>frame.length===128),'a full 32-pad sweep is attempted before controls');
frames.length=0;rejected=false;step();
assert(frames.some(frame=>frame.length===128),'rejected sweep retries next tick');
const notes=padMapFor(3);seqState.activeNotes[3*128+notes[0]]=1;
mask=0xffffffff;frames.length=0;step();
assert(frames.some(frame=>frame.length===128),'all sounding outputs can update in one frame despite control traffic');
mask=0;frames.length=0;step();
assert(frames.some(frame=>frame.length===128),'output note-offs clear all old green pads even with held input');
chord.setChordEnabled(false);invalidateInputModeLeds();frames.length=0;step();
assert(frames.some(frame=>frame.length===128),'mode handoff sweeps all pads');
console.log('Chord Play: priority pad frames, rejected-write retry, held-input clearing and mode sweep pass');
