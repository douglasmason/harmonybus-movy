import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
const temporary=mkdtempSync(join(tmpdir(),'hb-footer-'));
try{
    await build({entryPoints:[new URL('../src/renderer/hb-footer.ts',import.meta.url).pathname],bundle:true,format:'esm',outfile:join(temporary,'footer.mjs')});
    const {romanHarmony,harmonyFooterText,drawHarmonyFooter,queueFooterText,chordLabel,harmonyLabel,relativeFeedbackText}=await import(pathToFileURL(join(temporary,'footer.mjs')));
    const mask=(root,intervals)=>intervals.reduce((bits,interval)=>bits|1<<((root+interval)%12),0);
    assert.equal(romanHarmony(0,2,mask(2,[0,3,7,10])),'ii7');
    assert.equal(romanHarmony(0,7,mask(7,[0,4,7,10])),'V7');
    assert.equal(romanHarmony(0,11,mask(11,[0,3,6,10])),'viih7');
    assert.equal(romanHarmony(0,1,mask(1,[0,4,7])),'bII');
    assert.equal(romanHarmony(2,9,mask(9,[0,4,7,10])),'V7');
    assert.equal(romanHarmony(0,-1,0),'--');
    assert.match(harmonyFooterText(1,3,[0,1,2,mask(2,[0,3,7,10]),7,mask(7,[0,4,7,10])]),/Dm7 ii7 > G7 V7/);
    assert.match(harmonyFooterText(2,15,[0,9,-1,0,-1,0]),/-- > --/);
    assert.equal(chordLabel('D7','V/V'),'V/V');
    assert.equal(harmonyLabel(0,2,mask(2,[0,4,7,10]),2,7),'V/V');
    assert.equal(queueFooterText('G7','Hold 1/4'),'Next G7  Hold 1/4');
    const queue=(cursor,names)=>'cq1|2|4|C|G|1|0|2|1|'+cursor+'|'+names.length+'|'+names.join('|');
    assert.equal(queueFooterText('G','Loop 1/2',queue(0,['C','G'])),'Loop 1/2 [C] G');
    assert.equal(queueFooterText('C','Loop 2/2',queue(1,['C','C'])),'Loop 2/2 C [C]');
    assert.equal(queueFooterText('F','Loop 2/3',queue(1,['C','C','F'])),'Loop 2/3 C [C] F');
    assert.equal(queueFooterText('C','Loop 2/3',queue(1,['C','G','F'])),'Loop 2/3 C [G] F >C','a newly appended chord must not mislabel the already scheduled next chord');
    const names=['C','Dm7','Em7','F','G7','Am','Bdim','C7'];
    const middle=queueFooterText('G7','Loop 4/8',queue(3,names));assert.match(middle,/Loop 4\/8/);assert.match(middle,/Em7 \[F\] G7/);
    const last=queueFooterText('C','Loop 8/8',queue(7,names));assert.match(last,/Loop 8\/8/);assert.match(last,/Bdim \[C7\] C/);
    const first=queueFooterText('Dm7','Loop 1/8',queue(0,names));assert.match(first,/Loop 1\/8/);assert.match(first,/C7 \[C\] Dm7/);
    assert.equal(queueFooterText('G7','Hold 1/4','cq1|1|-1|C|G7|1|1|4|0|0|2|C|G7'),'Hold 1/4 [C] G7');
    assert.equal(queueFooterText('G7','Hold 1/4','cq1|1|-1|C|G7|1|1|4|0|0|16|C'),'Next G7  Hold 1/4','incomplete snapshots never invent a loop');
    assert.equal(harmonyFooterText(1,3),'P1 T4');
    await build({entryPoints:[new URL('../src/keyboard/relative-feedback.ts',import.meta.url).pathname],bundle:true,format:'esm',outfile:join(temporary,'feedback.mjs')});
    const {parseRelativeFeedback,RelativeFeedbackCache}=await import(pathToFileURL(join(temporary,'feedback.mjs')));
    const upper=parseRelativeFeedback('ro1,1,60,5,6,'+mask(6,[0,3,6,9])+',1,0,F,F#');
    assert.equal(relativeFeedbackText(upper),'F > UD F#dim7');
    const leading=parseRelativeFeedback('ro1,2,14,8,7,'+mask(7,[0,3,6,9])+',1,1,G#,G');
    assert.equal(relativeFeedbackText(leading),'G# > LT Gdim7');
    assert.equal(relativeFeedbackText({...upper,chord:false}),'F > UD F#');
    assert.equal(relativeFeedbackText({...upper,token:1}),'F > CCB F#dim7','connector label remains distinct from LT');
    assert.equal(harmonyFooterText(1,0,undefined,leading),'G# > LT Gdim7');
    for(const bad of ['ro1,1,4096,5,6,1,1,0,F,F#','ro1,1,60,12,6,1,1,0,F,F#','ro1,1,60,5,6,4096,1,0,F,F#','ro1,,60,5,6,1,1,0,F,F#','ro1,1,60,5,6,1,1,0,F,F#,extra'])assert.equal(parseRelativeFeedback(bad),undefined);
    const cache=new RelativeFeedbackCache();
    cache.observe(0,upper,0);assert.equal(cache.current(0,0),undefined,'initial read does not replay a stale event');
    assert.equal(cache.observe(0,leading,50),true);assert.equal(cache.current(0,50),leading);
    assert.equal(cache.current(1,50),undefined,'other tracks cannot borrow feedback');
    cache.observe(0,leading,500);assert.equal(cache.current(0,500),leading,'same serial does not restart timeout');
    assert.equal(cache.observe(0,leading,1900),true,'expiry invalidates the painted footer even after a late poll');
    assert.equal(cache.current(0,1900),undefined);
    cache.observe(0,{...leading,serial:3},2000);cache.observe(1,upper,2050);
    assert.equal(cache.current(1,2050),undefined);cache.observe(0,{...leading,serial:3},2100);assert.equal(cache.current(0,2100),undefined);
    cache.observe(0,{...leading,serial:4},2200);cache.clear();assert.equal(cache.current(0,2201),undefined);
    cache.observe(0,{...leading,serial:5},2300);cache.observe(0,{...leading,serial:6,token:0},2350);assert.equal(cache.current(0,2350),undefined,'plain notes clear the previous operation');
    cache.observe(0,{...leading,serial:7},2400);cache.observe(0,undefined,2450);assert.equal(cache.current(0,2450),undefined,'older native modules have no feedback');
    cache.observe(0,{...leading,serial:8},2500);cache.observe(0,{...leading,serial:9},2600);
    assert.equal(cache.expire(4401),true,'timeout clears even when native snapshot reads fail');
    const pixels=[];globalThis.fill_rect=(...args)=>pixels.push(args);
    drawHarmonyFooter('P1 T4 C Maj ii7  >  V7');const minorPixels=JSON.stringify(pixels);pixels.length=0;
    drawHarmonyFooter('P1 T4 C Maj II7  >  V7');assert.notEqual(JSON.stringify(pixels),minorPixels,'Minor Roman numerals are visibly lowercase');
    await build({entryPoints:[new URL('../src/font/index.ts',import.meta.url).pathname],bundle:true,format:'esm',outfile:join(temporary,'normal-font.mjs')});
    const {fontPrint}=await import(pathToFileURL(join(temporary,'normal-font.mjs')));
    pixels.length=0;fontPrint(1,58,'Min Live Overdub',1);const ordinary=JSON.stringify(pixels);
    pixels.length=0;drawHarmonyFooter('Min Live Overdub');assert.equal(JSON.stringify(pixels),ordinary,'ordinary words never use the small Roman font');
    pixels.length=0;fontPrint(1,58,'v',1);assert.equal(new Set(pixels.map(rect=>rect[1])).size,5);
    pixels.length=0;drawHarmonyFooter('v');assert.equal(new Set(pixels.map(rect=>rect[1])).size,3,'Roman lowercase retains exaggerated height');
    for(const name of ['Dm','Em','Am','Bdim','Bbmaj7','[Dm]','>Dm','C#m7b5','Dm/F']){
        pixels.length=0;fontPrint(1,58,name,1);const normal=JSON.stringify(pixels);
        pixels.length=0;drawHarmonyFooter(name);assert.notEqual(JSON.stringify(pixels),normal,name+' keeps contrasting chord spelling');
    }
    console.log('Footer: Roman quality, chromatic degrees, key-relative roots, scale and unknown next pass');
}finally{rmSync(temporary,{recursive:true,force:true});}
